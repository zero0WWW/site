import csv
import time

import requests

# ====== НАСТРОЙКИ ======
KEY = "3aa5a2da-c5fa-49da-a48a-c0ffbd843b9b"    # вставьте сюда ключ 2GIS
ГОРОД_ПО_УМОЛЧАНИЮ = "Талдыкорган"
СТРАНИЦ_НА_КАТЕГОРИЮ = 5  # демо-ключ отдаёт максимум 5 страниц по 10 заведений

КАТЕГОРИИ = [
    "салон красоты",
    "барбершоп",
    "ногтевая студия маникюр",
    "косметолог",
    "стоматология",
    "фитнес клуб",
    "фотостудия",
    "организация праздников",
    "ремонт квартир",
    "ресторан",
]
# =======================

ввод = input(f"Город (Enter = {ГОРОД_ПО_УМОЛЧАНИЮ}): ").strip()
ГОРОД = ввод or ГОРОД_ПО_УМОЛЧАНИЮ

найдено = {}  # id -> строка, чтобы не было повторов

for категория in КАТЕГОРИИ:
    print(f"Ищу: {категория}...")
    for страница in range(1, СТРАНИЦ_НА_КАТЕГОРИЮ + 1):
        try:
            ответ = requests.get(
                "https://catalog.api.2gis.com/3.0/items",
                params={
                    "q": f"{категория} {ГОРОД}",
                    "fields": "items.address_name",
                    "page": страница,
                    "page_size": 10,
                    "key": KEY,
                },
                timeout=20,
            ).json()
        except Exception as e:
            print("  Ошибка запроса:", e)
            break

        места = ответ.get("result", {}).get("items", [])
        if not места:
            if страница == 1:
                print("  Ничего не найдено. Ответ сервера:", ответ.get("meta", ответ))
            break

        for место in места:
            id_ = место.get("id")
            if id_ in найдено:
                continue
            найдено[id_] = [
                категория,
                место.get("name", ""),
                место.get("address_name", ""),
            ]
        time.sleep(0.5)

with open("leads.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["Категория", "Название", "Адрес", "Телефон", "Сайт есть?", "Instagram", "Статус"])
    for строка in найдено.values():
        w.writerow(строка + ["", "", "", ""])

print()
print(f"Готово. Найдено заведений: {len(найдено)}")
print("Список сохранён в leads.csv")
print("Телефон и наличие сайта впишите вручную (смотрите карточку на 2gis.kz).")
